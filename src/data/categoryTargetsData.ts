  0.0312, 0.0315, 0.0345, 0.0368, 0.0305, 0.0308, 0.0310, // Ngày 1 - 7
  0.0312, 0.0315, 0.0348, 0.0370, 0.0305, 0.0308, 0.0310, // Ngày 8 - 14
