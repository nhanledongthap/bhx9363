/**
 * Tính Target lũy kế đến ngày N (từ 1 đến 31)
 */
export function getCumulativeWeight(daysElapsed: number): number {
  const d = Math.max(1, Math.min(31, Math.round(daysElapsed)));
  let sum = 0;
  for (let i = 0; i < d; i++) {
    sum += DAILY_WEIGHTS_31_DAYS[i];
  }
  return sum;
}

/**
 * Lấy Target lũy kế N ngày của 1 ngành hàng cụ thể
 */
export function getCategoryCumulativeTarget(categoryName: string, daysElapsed: number): number {
  const fullMonth = OFFICIAL_CATEGORY_TOTAL_TARGETS[categoryName] || 0;
  return Math.round(fullMonth * getCumulativeWeight(daysElapsed));
}

/**
 * Lấy Target lũy kế N ngày của 1 Siêu Thị x 1 Ngành Hàng
 */
export function getStoreCategoryCumulativeTarget(storeCode: string, categoryName: string, daysElapsed: number): number {
  const storeMap = OFFICIAL_STORE_CATEGORY_TARGETS[storeCode];
  const fullMonth = storeMap ? (storeMap[categoryName] || 0) : 0;
  return Math.round(fullMonth * getCumulativeWeight(daysElapsed));
}
